const DICTIONARIES: Record<Locale, Record<I18nKey, string>> = { zh, en };

let currentLocale: Locale = 'zh';

export function setLocale(locale: Locale): void {
  currentLocale = locale;
  if (typeof document !== 'undefined') {
    document.documentElement.lang = locale === 'zh' ? 'zh-CN' : 'en';
  }
}

export function getLocale(): Locale {
  return currentLocale;
}

export function resolveLocale(
  preference: 'zh' | 'en' | 'auto' | undefined,
  systemLanguage: string,
): Locale {
  if (preference === 'zh' || preference === 'en') return preference;
  return systemLanguage.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

/**
 * 取文案。缺 key（迁移中）回退中文；变量用 `{name}` 插值。
 */
export function t(key: I18nKey, vars?: Record<string, string | number>): string {
  const table = DICTIONARIES[currentLocale] ?? DICTIONARIES.zh;
  const template = table[key] ?? DICTIONARIES.zh[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}
