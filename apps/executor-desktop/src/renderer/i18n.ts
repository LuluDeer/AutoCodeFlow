/**
 * N-04 桌面收尾：ConfigPage 渲染层双语文案表。
 *
 * 与主进程 tray-texts.ts 同范式（审计二轮 B-7② 先例）：双语常量表 + 语言判定
 * 抽成无依赖纯模块，行为可被 selftest 直接驱动。区别于 tray 的是本表走**扁平
 * 点号键**（对齐 admin-web locales 的命名空间风格），每行一条、zh/en 两块键序
 * 一致——renderer.selftest.mjs 据此做键位对齐断言（两语言必须提供同一组键，
 * 防止后续只改一种语言造成静默缺键）。
 *
 * 语言判定：navigator.language 前缀 `en*` → 英文，其余回落中文（与托盘
 * resolveTrayLocale 同口径；渲染层无运行时热切语言入口，重建组件时按当前
 * language 取表）。
 *
 * 取值走 createCfgTexts()：字符串直出，函数条目做插值（对齐 tray-texts 的
 * agentLine/agentProcessedLine 形态）；缺键回退键名本身（与 i18next 缺键
 * 行为一致，肉眼可见、不炸渲染——selftest 键位对齐保证正常情况下到不了）。
 *
 * 覆盖口径：ConfigPage.tsx 全部渲染层文案（标签/aria/placeholder/错误行/
 * 诊断块/确认弹层），不含注释。其余 renderer 页面（AppsPage/StatusWindow/
 * HistoryPage/Wizard）仍是硬编码中文，见 DESIGN-AUDIT-2026-09-22 的
 * renderer i18n 建议，逐页迁移时把文案搬进本表。
 */
export type RendererLocale = 'en' | 'zh';

/** `en*` 一律英文，其余 locale（zh-CN / fr / 空 / 未知）回落中文。 */
export function resolveRendererLocale(getLanguage: () => string): RendererLocale {
  return getLanguage().toLowerCase().startsWith('en') ? 'en' : 'zh';
}

/** 文案条目：字符串直出；函数做插值（参数按声明顺序传入）。 */
export type CfgTextEntry = string | ((...args: (string | number | boolean)[]) => string);

export type CfgTextTable = Record<string, CfgTextEntry>;

/** 生成取值函数：t('cfg.conn.title') / t('cfg.python.poolReady', n, list)。 */
export function createCfgTexts(locale: RendererLocale): (
  key: string,
  ...args: (string | number | boolean)[]
) => string {
  const table: CfgTextTable = CFG_TEXTS[locale];
  return (key, ...args) => {
    const entry = table[key];
    if (entry == null) return key; // 缺键：回退键名（selftest 键位对齐兜底）
    return typeof entry === 'function' ? entry(...args) : entry;
  };
}

