#!/usr/bin/env node
// E-38（DEEP_REVIEW 0ef3bbe）：install.sh 双拷贝根治。
//
// 旧形态：scripts/install.sh 与 apps/admin-api/src/modules/executor/
// install-script.content.ts 各存一份 260+ 行脚本，靠人工同步 + 运行期
// repoInstallScriptOrNull() 比对（dist 部署形态仓库根不可达时返回 null 直接跳过）。
// 任何一侧改了只落一份即静默分叉。
//
// 现形态：scripts/install.sh 是唯一事实源；本脚本在构建期读它、用 JSON.stringify
// 转义（自动处理反斜杠/反引号/${}/换行，不再手工写 \$ 转义），重新生成
// install-script.content.ts。修改安装脚本只改 install.sh，跑本脚本（或 prebuild
// 自动跑）即可。CI 守卫：跑本脚本后 git diff --exit-code，未同步即红。
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const shPath = resolve(repoRoot, "scripts/install.sh");
const outPath = resolve(
  repoRoot,
  "apps/admin-api/src/modules/executor/install-script.content.ts",
);

const sh = readFileSync(shPath, "utf8");

const header = [
  "// AUTO-GENERATED by scripts/gen-install-script-content.mjs - DO NOT EDIT BY HAND.",
  "// E-38（DEEP_REVIEW 0ef3bbe）：install.sh 的唯一事实源是 scripts/install.sh；本文件",
  "// 由构建期脚本从它生成（JSON.stringify 转义，避免手工维护两份 260 行脚本漂移）。",
  "// 修改安装脚本请改 scripts/install.sh 后跑 npm run gen:install-script（或 prebuild 自动跑）。",
  "// CI 会 git diff --exit-code 守卫两者一致。",
  'import { readFileSync } from "fs";',
  'import { resolve } from "path";',
  "",
  "/**",
  " * install.sh 的后端承载副本：GET /api/executors/install.sh 以此常量作为",
  " * text/plain 响应体下发，供目标机 curl | bash 安装执行器。",
  " */",
  "export const INSTALL_SCRIPT = " + JSON.stringify(sh) + ";",
  "",
  "/**",
  " * 测试守卫用：校验常量与仓库根 scripts/install.sh 逐字节一致（防两副本漂移）。",
  " * 构建产物（dist）中仓库根不可达时返回 null，调用方自行跳过。",
  " */",
  "export function repoInstallScriptOrNull(): string | null {",
  "  try {",
  '    const p = resolve(__dirname, "../../../../../scripts/install.sh");',
  '    return readFileSync(p, "utf8");',
  "  } catch {",
  "    return null;",
  "  }",
  "}",
  "",
].join("\n");

writeFileSync(outPath, header, "utf8");
console.log("[gen:install-script] wrote " + outPath + " from " + shPath);
