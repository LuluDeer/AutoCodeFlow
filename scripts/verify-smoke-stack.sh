#!/usr/bin/env bash
#
# verify-smoke-stack.sh —— 本轮「compose 真机冒烟」的**栈生命周期管理**脚本。
#
# 用途：起/停一个**完全隔离**的 admin-api + PG16 + Redis7 栈，供
#       verify-smoke-*.sh 系列做真机验证。与仓库既有生产栈（compose 项目
#       `acf`）**完全隔离**：
#         · 独立容器名（acfsmoke-*）
#         · 独立 docker network（acfsmoke-net）
#         · 独立卷（acfsmoke-uploads）
#         · 独立宿主端口（默认 55432 / 56379 / 43105，默认值经 tcp 探测避让）
#         · 独立随机口令（每次运行重新生成，不写回仓库 .env）
#
# 为什么不用 scripts/demo.sh：demo.sh 起的是**完整 8 服务栈**（含两个
# registry + 两个执行器 + admin-web），本轮验证只需 admin-api + PG + Redis；
# demo.sh 还会占用 8088/3105/8001/8002（宿主已有 acf 栈占用 3105/8088）。
#
# 为什么不用根 docker-compose.yml：它带 `env_file: .env`（会读生产 .env 的
# 口令与 CORS 白名单）且端口 3105 与现网冲突。本脚本**只读**根 compose
# 做镜像构建上下文参考，不消费它的服务定义。
#
# 用法：
#   ./scripts/verify-smoke-stack.sh up       # 起栈（幂等：已起则复用）
#   ./scripts/verify-smoke-stack.sh down     # 停栈并**彻底删除**容器/网络/卷
#   ./scripts/verify-smoke-stack.sh env       # 打印导出变量（供其它脚本 source）
#   ./scripts/verify-smoke-stack.sh status
#
# 退出码：0 = 成功；非 0 = 失败（调用方据此判 FAIL）。
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

# ── 栈标识（全部 acfsmoke-* 前缀 ⇒ 清理时不会误伤现网）──────────────────
STACK_NAME="${ACF_SMOKE_STACK:-acfsmoke}"
PG_CONTAINER="${STACK_NAME}-postgres"
REDIS_CONTAINER="${STACK_NAME}-redis"
API_CONTAINER="${STACK_NAME}-admin-api"
NETWORK="${STACK_NAME}-net"
UPLOAD_VOLUME="${STACK_NAME}-uploads"
IMAGE="${ACF_SMOKE_IMAGE:-acf-smoke-admin-api:r5}"

# 宿主端口（默认避开现网常用端口；可用环境变量覆盖）
PG_PORT="${ACF_SMOKE_PG_PORT:-55432}"
REDIS_PORT="${ACF_SMOKE_REDIS_PORT:-56379}"
API_PORT="${ACF_SMOKE_API_PORT:-43105}"

PG_USER="autoflow"
PG_DB="autoflow"

# 口令文件（放 /tmp，不进仓库；每次 up 重新生成）
ENV_FILE="${ACF_SMOKE_ENV_FILE:-/tmp/acf-smoke-env.sh}"

log() { printf '[smoke-stack] %s\n' "$*"; }
die() { printf '[smoke-stack] ✗ %s\n' "$*" >&2; exit 1; }

require_docker() {
  command -v docker >/dev/null 2>&1 || die "docker not found"
  docker info >/dev/null 2>&1 || die "cannot talk to the Docker daemon"
}

# 端口占用探测：只在端口真的被占时报错（避免误伤别的栈）
port_free() {
  ! (exec 3<>"/dev/tcp/127.0.0.1/$1") 2>/dev/null
}

gen_secret() {
  # 32+ 字符强随机（生产 fail-fast 要求 JWT_SECRET >= 32 字符）
  node -e 'const c=require("crypto");process.stdout.write("Sm"+c.randomBytes(32).toString("base64url"))'
}

write_env_file() {
  cat >"$ENV_FILE" <<EOF
# generated by scripts/verify-smoke-stack.sh — 一次性隔离栈口令，勿入库
export SMOKE_STACK="${STACK_NAME}"
export SMOKE_PG_CONTAINER="${PG_CONTAINER}"
export SMOKE_REDIS_CONTAINER="${REDIS_CONTAINER}"
export SMOKE_API_CONTAINER="${API_CONTAINER}"
export SMOKE_NET="${NETWORK}"
export SMOKE_IMAGE="${IMAGE}"
export SMOKE_PG_PORT="${PG_PORT}"
export SMOKE_REDIS_PORT="${REDIS_PORT}"
export SMOKE_API_PORT="${API_PORT}"
export SMOKE_PG_USER="${PG_USER}"
export SMOKE_PG_DB="${PG_DB}"
export SMOKE_PG_PASSWORD="$(gen_secret)"
export SMOKE_REDIS_PASSWORD="$(gen_secret)"
export SMOKE_JWT_SECRET="$(gen_secret)"
export SMOKE_JWT_REFRESH="$(gen_secret)"
export SMOKE_EXEC_SECRET="$(gen_secret)"
export SMOKE_ADMIN_PW="Sm$(gen_secret)"
export SMOKE_ADMIN_MAIL="smoke-admin@acf-smoke.local"
EOF
  chmod 600 "$ENV_FILE"
}

load_env_file() {
  [[ -f "$ENV_FILE" ]] || die "env file $ENV_FILE not found — run 'up' first"
  # shellcheck disable=SC1090
  source "$ENV_FILE"
}

wait_for() {
  # wait_for <描述> <命令...>：最多等 90 秒
  local desc="$1"; shift
  local i
  for i in $(seq 1 90); do
    if "$@" >/dev/null 2>&1; then
      log "$desc ready"
      return 0
    fi
    sleep 1
  done
  die "$desc did not become ready within 90s"
}

pg_ready() {
  docker exec "$PG_CONTAINER" pg_isready -U "$PG_USER" -d "$PG_DB" >/dev/null 2>&1
}

redis_ready() {
  docker exec "$REDIS_CONTAINER" redis-cli -a "$SMOKE_REDIS_PASSWORD" ping 2>/dev/null | grep -q PONG
}

api_ready() {
  curl -fsS "http://127.0.0.1:${API_PORT}/api/health/live" >/dev/null 2>&1
}

build_image() {
  log "building admin-api image $IMAGE (this is the slow step)"
  docker build -f apps/admin-api/Dockerfile -t "$IMAGE" apps/admin-api
}

cmd_up() {
  require_docker
  for p in "$PG_PORT" "$REDIS_PORT" "$API_PORT"; do
    port_free "$p" || die "host port $p is already in use — override with ACF_SMOKE_*_PORT"
  done
  write_env_file
  load_env_file

  if [[ "${ACF_SMOKE_SKIP_BUILD:-0}" != "1" ]]; then
    build_image
  else
    docker image inspect "$IMAGE" >/dev/null 2>&1 || die "image $IMAGE missing"
  fi

  docker network inspect "$NETWORK" >/dev/null 2>&1 || docker network create "$NETWORK" >/dev/null

  docker rm -f "$PG_CONTAINER" "$REDIS_CONTAINER" "$API_CONTAINER" >/dev/null 2>&1 || true

  log "starting postgres + redis"
  docker run -d --name "$PG_CONTAINER" --network "$NETWORK" \
    -p "127.0.0.1:${PG_PORT}:5432" \
    -e POSTGRES_USER="$PG_USER" -e POSTGRES_PASSWORD="$SMOKE_PG_PASSWORD" -e POSTGRES_DB="$PG_DB" \
    postgres:16-alpine >/dev/null
  docker run -d --name "$REDIS_CONTAINER" --network "$NETWORK" \
    -p "127.0.0.1:${REDIS_PORT}:6379" \
    redis:7-alpine redis-server --requirepass "$SMOKE_REDIS_PASSWORD" \
      --maxmemory 256mb --maxmemory-policy noeviction --appendonly yes >/dev/null

  wait_for "postgres" pg_ready
  wait_for "redis" redis_ready

  log "starting admin-api (migrations run at boot)"
  # R05（2026-11-05）：契约口径下 `privateIPv4` 需开关才放行，而本栈的调度目标是
  # 同一 docker 网络里的执行器（解析到 172.x 私网）⇒ admin-api 侧**必须**开启，
  # 否则所有派发被 SSRF 闸拒（`EXECUTOR_HOST_BLOCKED`）。与根 compose 的默认值一致；
  # 「默认姿态（拒绝）」由 verify-smoke-dispatch-push 的 B4 用「摘掉该 env 重建」验证。
  docker run -d --name "$API_CONTAINER" --network "$NETWORK" \
    -p "127.0.0.1:${API_PORT}:3105" \
    -e NODE_ENV=production \
    -e LOG_LEVEL="${ACF_SMOKE_LOG_LEVEL:-debug}" \
    -e PORT=3105 \
    -e DB_HOST="$PG_CONTAINER" -e DB_PORT=5432 \
    -e DB_USERNAME="$PG_USER" -e DB_PASSWORD="$SMOKE_PG_PASSWORD" -e DB_DATABASE="$PG_DB" \
    -e REDIS_HOST="$REDIS_CONTAINER" -e REDIS_PORT=6379 -e REDIS_PASSWORD="$SMOKE_REDIS_PASSWORD" \
    -e JWT_SECRET="$SMOKE_JWT_SECRET" -e JWT_REFRESH_SECRET="$SMOKE_JWT_REFRESH" \
    -e EXECUTOR_SECRET="$SMOKE_EXEC_SECRET" \
    -e EXECUTOR_ALLOW_PRIVATE_NETWORK=true \
    -e INITIAL_ADMIN_PASSWORD="$SMOKE_ADMIN_PW" -e INITIAL_ADMIN_EMAIL="$SMOKE_ADMIN_MAIL" \
    -e CORS_ALLOWED_ORIGINS=http://localhost:8088 -e ALLOW_LOOPBACK_CORS=true \
    -e ADMIN_WEB_ORIGIN=http://localhost:8088 \
    -e API_BASE_URL="http://${API_CONTAINER}:3105" \
    -v "${UPLOAD_VOLUME}:/app/uploads" \
    "$IMAGE" >/dev/null

  wait_for "admin-api" api_ready
  log "stack up: api=http://127.0.0.1:${API_PORT} pg=127.0.0.1:${PG_PORT} redis=127.0.0.1:${REDIS_PORT}"
  log "env file: $ENV_FILE"
}

cmd_down() {
  require_docker
  docker rm -f "$API_CONTAINER" "$REDIS_CONTAINER" "$PG_CONTAINER" >/dev/null 2>&1 || true
  docker network rm "$NETWORK" >/dev/null 2>&1 || true
  docker volume rm "$UPLOAD_VOLUME" >/dev/null 2>&1 || true
  rm -f "$ENV_FILE"
  log "stack torn down (containers/network/volume/env removed)"
}

cmd_status() {
  require_docker
  docker ps -a --filter "name=${STACK_NAME}" --format '{{.Names}}\t{{.Status}}\t{{.Ports}}'
}

case "${1:-up}" in
  up) cmd_up ;;
  down) cmd_down ;;
  env)
    load_env_file
    env | grep '^SMOKE_' | sort
    ;;
  status) cmd_status ;;
  *) echo "usage: $0 {up|down|env|status}" >&2; exit 2 ;;
esac
