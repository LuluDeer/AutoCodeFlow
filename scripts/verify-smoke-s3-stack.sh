#!/usr/bin/env bash
#
# verify-smoke-s3-stack.sh —— S3 日志链路的**隔离栈**（PG + Redis + RustFS + admin-api@s3）。
#
# 与 `verify-smoke-stack.sh`（R5 那一套）的关系：**同一个隔离栈，多加一个 RustFS**，
# 并且 admin-api 换成 `LOG_STORAGE_DRIVER=s3` 模式。
#
# ## 为什么自己起 RustFS 而不用 compose profile
#
# · `docker-compose.yml` 的 rustfs 服务在 `profiles: ['rustfs']` 下，用
#   `docker compose --profile rustfs up -d rustfs` 会**顺带拉起 21 个服务里的
#   其它 13 个**、并且走根 `.env`（生产口令）——本轮要的是**完全隔离**。
# · compose 里 `rustfs` 依赖一次性 `volume-permission-helper`（alpine chown
#   10001:10001）。手工 `docker run` 起 rustfs **必须自己 chown**，否则
#   实测报 `Permission denied (os error 13)`（`docs/deployment.md:826` 已记，
#   本脚本照做）。
# · 宿主端口用 59000/59001（避开 compose 的 9000/9001 与现网）。
#
# ## 用法
#   ./scripts/verify-smoke-s3-stack.sh up     # 起栈（PG+Redis+RustFS+admin-api@s3）
#   ./scripts/verify-smoke-s3-stack.sh down   # 彻底删除容器/网络/卷/临时口令
#   ./scripts/verify-smoke-s3-stack.sh env    # 打印导出变量
#   ./scripts/verify-smoke-s3-stack.sh mc     # 用 mc(minio client) 列 bucket 内容
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

STACK_NAME="${ACF_SMOKE_STACK:-acfsmoke}"
PG_CONTAINER="${STACK_NAME}-postgres"
REDIS_CONTAINER="${STACK_NAME}-redis"
RUSTFS_CONTAINER="${STACK_NAME}-rustfs"
API_CONTAINER="${STACK_NAME}-admin-api"
NETWORK="${STACK_NAME}-net"
UPLOAD_VOLUME="${STACK_NAME}-uploads"
RUSTFS_DATA_VOLUME="${STACK_NAME}-rustfs-data"
RUSTFS_LOGS_VOLUME="${STACK_NAME}-rustfs-logs"
IMAGE="${ACF_SMOKE_IMAGE:-acf-smoke-admin-api:r5}"
RUSTFS_IMAGE="${ACF_SMOKE_RUSTFS_IMAGE:-docker.1ms.run/rustfs/rustfs:1.0.4}"

PG_PORT="${ACF_SMOKE_PG_PORT:-55432}"
REDIS_PORT="${ACF_SMOKE_REDIS_PORT:-56379}"
API_PORT="${ACF_SMOKE_API_PORT:-43105}"
RUSTFS_PORT="${ACF_SMOKE_RUSTFS_PORT:-59000}"
RUSTFS_CONSOLE_PORT="${ACF_SMOKE_RUSTFS_CONSOLE_PORT:-59001}"

PG_USER="autoflow"
PG_DB="autoflow"
# RustFS 凭证（compose 同款纪律：secret 无默认值，必须显式给）
RUSTFS_ACCESS_KEY="smokeak"
RUSTFS_SECRET_KEY="SmokeRustFs-Secret-9xK2mP7q"
LOG_BUCKET="autoflow-logs"

ENV_FILE="${ACF_SMOKE_ENV_FILE:-/tmp/acf-smoke-env.sh}"

log() { printf '[smoke-s3-stack] %s\n' "$*"; }
die() { printf '[smoke-s3-stack] ✗ %s\n' "$*" >&2; exit 1; }
require_docker() {
  command -v docker >/dev/null 2>&1 || die "docker not found"
  docker info >/dev/null 2>&1 || die "cannot talk to the Docker daemon"
}
port_free() { ! (exec 3<>"/dev/tcp/127.0.0.1/$1") 2>/dev/null; }
gen_secret() { node -e 'const c=require("crypto");process.stdout.write("Sm"+c.randomBytes(32).toString("base64url"))'; }
wait_for() {
  local desc="$1"; shift
  for _ in $(seq 1 90); do
    if "$@" >/dev/null 2>&1; then log "$desc ready"; return 0; fi
    sleep 1
  done
  die "$desc did not become ready within 90s"
}
pg_ready()    { docker exec "$PG_CONTAINER" pg_isready -U "$PG_USER" -d "$PG_DB" >/dev/null 2>&1; }
redis_ready() { docker exec "$REDIS_CONTAINER" redis-cli -a "$SMOKE_REDIS_PASSWORD" ping 2>/dev/null | grep -q PONG; }
rustfs_ready(){ curl -fsS "http://127.0.0.1:${RUSTFS_PORT}/health" >/dev/null 2>&1; }
api_ready()   { curl -fsS "http://127.0.0.1:${API_PORT}/api/health/live" >/dev/null 2>&1; }

write_env_file() {
  cat >"$ENV_FILE" <<EOF
# generated by scripts/verify-smoke-s3-stack.sh — 一次性隔离栈口令，勿入库
export SMOKE_STACK="${STACK_NAME}"
export SMOKE_PG_CONTAINER="${PG_CONTAINER}"
export SMOKE_REDIS_CONTAINER="${REDIS_CONTAINER}"
export SMOKE_RUSTFS_CONTAINER="${RUSTFS_CONTAINER}"
export SMOKE_API_CONTAINER="${API_CONTAINER}"
export SMOKE_NET="${NETWORK}"
export SMOKE_IMAGE="${IMAGE}"
export SMOKE_PG_PORT="${PG_PORT}"
export SMOKE_REDIS_PORT="${REDIS_PORT}"
export SMOKE_API_PORT="${API_PORT}"
export SMOKE_RUSTFS_PORT="${RUSTFS_PORT}"
export SMOKE_RUSTFS_CONSOLE_PORT="${RUSTFS_CONSOLE_PORT}"
export SMOKE_PG_USER="${PG_USER}"
export SMOKE_PG_DB="${PG_DB}"
export SMOKE_PG_PASSWORD="$(gen_secret)"
export SMOKE_REDIS_PASSWORD="$(gen_secret)"
export SMOKE_JWT_SECRET="$(gen_secret)"
export SMOKE_JWT_REFRESH="$(gen_secret)"
export SMOKE_EXEC_SECRET="$(gen_secret)"
export SMOKE_ADMIN_PW="Sm$(gen_secret)"
export SMOKE_ADMIN_MAIL="smoke-admin@acf-smoke.local"
export SMOKE_RUSTFS_ACCESS_KEY="${RUSTFS_ACCESS_KEY}"
export SMOKE_RUSTFS_SECRET_KEY="${RUSTFS_SECRET_KEY}"
export SMOKE_LOG_BUCKET="${LOG_BUCKET}"
# 派生键（容器内可达的地址）——统一入口 scripts/verify-smoke-all.sh 按**变量名**
# 透传这些键，故它们必须是「名字 → 值」的完整形态，不能由调用方拼。
export SMOKE_RUSTFS_ENDPOINT="${RUSTFS_CONTAINER}:9000"
export SMOKE_API_URL="http://127.0.0.1:3105/api"
EOF
  chmod 600 "$ENV_FILE"
}
load_env_file() {
  [[ -f "$ENV_FILE" ]] || die "env file $ENV_FILE not found — run 'up' first"
  # shellcheck disable=SC1090
  source "$ENV_FILE"
}

cmd_up() {
  require_docker
  for p in "$PG_PORT" "$REDIS_PORT" "$API_PORT" "$RUSTFS_PORT" "$RUSTFS_CONSOLE_PORT"; do
    port_free "$p" || die "host port $p is already in use — override with ACF_SMOKE_*_PORT"
  done
  write_env_file
  load_env_file

  if [[ "${ACF_SMOKE_SKIP_BUILD:-0}" != "1" ]]; then
    log "building admin-api image $IMAGE"
    docker build -f apps/admin-api/Dockerfile -t "$IMAGE" apps/admin-api
  else
    docker image inspect "$IMAGE" >/dev/null 2>&1 || die "image $IMAGE missing"
  fi
  docker image inspect "$RUSTFS_IMAGE" >/dev/null 2>&1 \
    || die "rustfs image $RUSTFS_IMAGE not present locally (docker pull it first)"

  docker network inspect "$NETWORK" >/dev/null 2>&1 || docker network create "$NETWORK" >/dev/null
  docker rm -f "$PG_CONTAINER" "$REDIS_CONTAINER" "$RUSTFS_CONTAINER" "$API_CONTAINER" >/dev/null 2>&1 || true

  log "starting postgres + redis"
  docker run -d --name "$PG_CONTAINER" --network "$NETWORK" \
    -p "127.0.0.1:${PG_PORT}:5432" \
    -e POSTGRES_USER="$PG_USER" -e POSTGRES_PASSWORD="$SMOKE_PG_PASSWORD" -e POSTGRES_DB="$PG_DB" \
    postgres:16-alpine >/dev/null
  docker run -d --name "$REDIS_CONTAINER" --network "$NETWORK" \
    -p "127.0.0.1:${REDIS_PORT}:6379" \
    redis:7-alpine redis-server --requirepass "$SMOKE_REDIS_PASSWORD" \
      --maxmemory 256mb --maxmemory-policy noeviction --appendonly yes >/dev/null
  wait_for "postgres" pg_ready
  wait_for "redis" redis_ready

  log "starting rustfs (chown volumes to 10001:10001 first — 见 docs/deployment.md:826)"
  # ⚠️ rustfs 以非 root 10001:10001 运行，docker 新建命名卷属主是 root ⇒
  # 必须先 chown，否则启动即 `Permission denied (os error 13)`。
  docker run --rm \
    -v "${RUSTFS_DATA_VOLUME}:/data/rustfs0" -v "${RUSTFS_LOGS_VOLUME}:/app/logs" \
    alpine:3.20 sh -c 'chown -R 10001:10001 /data/rustfs0 /app/logs'
  docker run -d --name "$RUSTFS_CONTAINER" --network "$NETWORK" \
    -p "127.0.0.1:${RUSTFS_PORT}:9000" -p "127.0.0.1:${RUSTFS_CONSOLE_PORT}:9001" \
    -e RUSTFS_VOLUMES=/data/rustfs0 \
    -e RUSTFS_ADDRESS=0.0.0.0:9000 -e RUSTFS_CONSOLE_ADDRESS=0.0.0.0:9001 \
    -e RUSTFS_CONSOLE_ENABLE=true \
    -e RUSTFS_ACCESS_KEY="$RUSTFS_ACCESS_KEY" -e RUSTFS_SECRET_KEY="$RUSTFS_SECRET_KEY" \
    -e RUSTFS_OBS_LOGGER_LEVEL=info -e RUSTFS_OBS_LOG_DIRECTORY=/app/logs \
    -v "${RUSTFS_DATA_VOLUME}:/data/rustfs0" -v "${RUSTFS_LOGS_VOLUME}:/app/logs" \
    "$RUSTFS_IMAGE" >/dev/null
  wait_for "rustfs" rustfs_ready

  log "starting admin-api with LOG_STORAGE_DRIVER=s3"
  docker run -d --name "$API_CONTAINER" --network "$NETWORK" \
    -p "127.0.0.1:${API_PORT}:3105" \
    -e NODE_ENV=production -e LOG_LEVEL="${ACF_SMOKE_LOG_LEVEL:-debug}" -e PORT=3105 \
    -e DB_HOST="$PG_CONTAINER" -e DB_PORT=5432 \
    -e DB_USERNAME="$PG_USER" -e DB_PASSWORD="$SMOKE_PG_PASSWORD" -e DB_DATABASE="$PG_DB" \
    -e REDIS_HOST="$REDIS_CONTAINER" -e REDIS_PORT=6379 -e REDIS_PASSWORD="$SMOKE_REDIS_PASSWORD" \
    -e JWT_SECRET="$SMOKE_JWT_SECRET" -e JWT_REFRESH_SECRET="$SMOKE_JWT_REFRESH" \
    -e EXECUTOR_SECRET="$SMOKE_EXEC_SECRET" \
    -e INITIAL_ADMIN_PASSWORD="$SMOKE_ADMIN_PW" -e INITIAL_ADMIN_EMAIL="$SMOKE_ADMIN_MAIL" \
    -e CORS_ALLOWED_ORIGINS=http://localhost:8088 -e ALLOW_LOOPBACK_CORS=true \
    -e ADMIN_WEB_ORIGIN=http://localhost:8088 -e API_BASE_URL="http://${API_CONTAINER}:3105" \
    -e LOG_STORAGE_DRIVER=s3 \
    -e LOG_STORAGE_ENDPOINT="${RUSTFS_CONTAINER}:9000" \
    -e LOG_STORAGE_BUCKET="$LOG_BUCKET" \
    -e LOG_STORAGE_ACCESS_KEY="$RUSTFS_ACCESS_KEY" \
    -e LOG_STORAGE_SECRET_KEY="$RUSTFS_SECRET_KEY" \
    -e LOG_STORAGE_USE_SSL=false \
    -v "${UPLOAD_VOLUME}:/app/uploads" \
    "$IMAGE" >/dev/null
  wait_for "admin-api" api_ready
  log "stack up: api=http://127.0.0.1:${API_PORT} rustfs=http://127.0.0.1:${RUSTFS_PORT} pg=${PG_PORT} redis=${REDIS_PORT}"
  log "env file: $ENV_FILE"
}

cmd_down() {
  require_docker
  docker rm -f "$API_CONTAINER" "$RUSTFS_CONTAINER" "$REDIS_CONTAINER" "$PG_CONTAINER" >/dev/null 2>&1 || true
  docker network rm "$NETWORK" >/dev/null 2>&1 || true
  docker volume rm "$UPLOAD_VOLUME" "$RUSTFS_DATA_VOLUME" "$RUSTFS_LOGS_VOLUME" >/dev/null 2>&1 || true
  rm -f "$ENV_FILE"
  log "stack torn down (containers/network/volumes/env removed)"
}

cmd_env() { load_env_file; env | grep '^SMOKE_' | sort; }

# 用 admin-api 镜像里的 minio 客户端（npm minio 包自带 mc 二进制）在容器内
# 列 bucket —— 这是「对象真的存在」最直接的证据。
cmd_mc() {
  load_env_file
  docker exec -e MC_HOST_smoke="http://${SMOKE_RUSTFS_ACCESS_KEY}:${SMOKE_RUSTFS_SECRET_KEY}@${RUSTFS_CONTAINER}:9000" \
    "$API_CONTAINER" sh -c 'mc alias set smoke "$MC_HOST_smoke" >/dev/null 2>&1; mc ls -r smoke/ 2>&1' || true
}

case "${1:-up}" in
  up) cmd_up ;;
  down) cmd_down ;;
  env) cmd_env ;;
  mc) cmd_mc ;;
  status) require_docker; docker ps -a --filter "name=${STACK_NAME}" --format '{{.Names}}\t{{.Status}}\t{{.Ports}}' ;;
  *) echo "usage: $0 {up|down|env|mc|status}" >&2; exit 2 ;;
esac
